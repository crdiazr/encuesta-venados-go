-- ---------- Tablas ----------

-- Grupos: en la prueba son las generaciones de Pokémon. Cuando cambies de personajes,
-- aquí van las categorías nuevas (temporadas, casas, equipos, etc.).
create table if not exists public.grupos (
  id         int primary key,
  nombre     text not null,
  subtitulo  text not null default '',
  orden      int  not null default 0
);

create table if not exists public.personajes (
  id          bigint generated by default as identity primary key,
  grupo_id    int  not null references public.grupos(id) on delete cascade,
  nombre      text not null,
  imagen_url  text,
  numero      int,              -- número que se muestra en la tarjeta (en Pokémon, el de la Pokédex)
  activo      boolean not null default true
);
create index if not exists personajes_grupo_idx on public.personajes (grupo_id, numero);
create index if not exists personajes_nombre_idx on public.personajes (lower(nombre));

-- Votos: un registro por persona. El correo y la cuenta verificada son únicos,
-- así que la base de datos rechaza un segundo voto.
create table if not exists public.votos (
  id              bigint generated always as identity primary key,
  personaje_id    bigint not null references public.personajes(id) on delete restrict,
  usuario_id      uuid   not null unique references auth.users(id) on delete cascade,
  correo          text   not null unique,
  nombre_usuario  text   not null check (char_length(nombre_usuario) between 2 and 40),
  creado_en       timestamptz not null default now()
);
create index if not exists votos_personaje_idx on public.votos (personaje_id);

create table if not exists public.administradores (
  correo        text primary key check (correo = lower(correo) and correo like '%_@_%._%'),
  agregado_por  text,
  agregado_en   timestamptz not null default now()
);

-- ---------- Seguridad (Row Level Security) ----------
-- Todo el mundo puede VER grupos y personajes.
-- Nadie puede leer ni escribir votos o administradores directamente:
-- solo a través de las funciones de abajo, que revisan quién eres.

alter table public.grupos          enable row level security;
alter table public.personajes      enable row level security;
alter table public.votos           enable row level security;
alter table public.administradores enable row level security;

drop policy if exists "grupos visibles" on public.grupos;
create policy "grupos visibles" on public.grupos for select to anon, authenticated using (true);

drop policy if exists "personajes visibles" on public.personajes;
create policy "personajes visibles" on public.personajes for select to anon, authenticated using (activo);

grant select on public.grupos, public.personajes to anon, authenticated;
revoke all on public.votos, public.administradores from anon, authenticated;

-- ---------- Funciones ----------

-- ¿La persona con sesión iniciada es administradora?
create or replace function public.es_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.administradores
    where correo = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create or replace function public._exigir_admin()
returns void
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.es_admin() then
    raise exception 'Solo los administradores pueden hacer esto' using errcode = '42501';
  end if;
end;
$$;

-- Registrar el voto. Solo funciona después de verificar el correo con el código,
-- porque el correo se toma de la sesión verificada (no de lo que escriba la persona).
create or replace function public.emitir_voto(p_personaje_id bigint, p_nombre_usuario text)
returns json
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_usuario   uuid := auth.uid();
  v_correo    text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_nombre    text := btrim(coalesce(p_nombre_usuario, ''));
  v_personaje text;
  v_previo    text;
begin
  if v_usuario is null or v_correo = '' then
    raise exception 'Primero verifica tu correo con el código' using errcode = '42501';
  end if;

  -- ¿Ya votó antes? (por cuenta o por correo)
  select p.nombre into v_previo
  from public.votos v join public.personajes p on p.id = v.personaje_id
  where v.usuario_id = v_usuario or v.correo = v_correo
  limit 1;
  if v_previo is not null then
    return json_build_object('estado', 'ya_voto', 'personaje', v_previo);
  end if;

  if char_length(v_nombre) < 2 or char_length(v_nombre) > 40 then
    raise exception 'El nombre de usuario debe tener entre 2 y 40 caracteres' using errcode = '22023';
  end if;

  select nombre into v_personaje from public.personajes where id = p_personaje_id and activo;
  if v_personaje is null then
    raise exception 'Ese personaje no existe' using errcode = '22023';
  end if;

  insert into public.votos (personaje_id, usuario_id, correo, nombre_usuario)
  values (p_personaje_id, v_usuario, v_correo, v_nombre)
  on conflict do nothing;

  if not found then  -- dos envíos al mismo tiempo: gana el primero
    select p.nombre into v_previo
    from public.votos v join public.personajes p on p.id = v.personaje_id
    where v.usuario_id = v_usuario or v.correo = v_correo limit 1;
    return json_build_object('estado', 'ya_voto', 'personaje', v_previo);
  end if;

  return json_build_object('estado', 'ok', 'personaje', v_personaje);
end;
$$;

-- Resumen para el dashboard: total y votos por grupo.
create or replace function public.resumen_votos()
returns json
language plpgsql stable security definer set search_path = ''
as $$
declare r json;
begin
  perform public._exigir_admin();
  select json_build_object(
    'total',               (select count(*) from public.votos),
    'personajes_votados',  (select count(distinct personaje_id) from public.votos),
    'ultimo_voto',         (select max(creado_en) from public.votos),
    'por_grupo', coalesce((
      select json_agg(json_build_object('id', g.id, 'nombre', g.nombre, 'subtitulo', g.subtitulo, 'votos', g.votos) order by g.orden)
      from (
        select gr.id, gr.nombre, gr.subtitulo, gr.orden, count(v.id) as votos
        from public.grupos gr
        left join public.personajes p on p.grupo_id = gr.id
        left join public.votos v on v.personaje_id = p.id
        group by gr.id
      ) g
    ), '[]'::json)
  ) into r;
  return r;
end;
$$;

-- Ranking de personajes por votos (opcionalmente de un solo grupo).
create or replace function public.ranking_personajes(p_grupo_id int default null, p_limite int default 100)
returns table (posicion bigint, personaje_id bigint, nombre text, imagen_url text, numero int, grupo text, votos bigint)
language plpgsql stable security definer set search_path = ''
as $$
#variable_conflict use_column
begin
  perform public._exigir_admin();
  return query
    select rank() over (order by count(v.id) desc) as posicion,
           p.id, p.nombre, p.imagen_url, p.numero, g.nombre, count(v.id) as votos
    from public.votos v
    join public.personajes p on p.id = v.personaje_id
    join public.grupos g on g.id = p.grupo_id
    where p_grupo_id is null or p.grupo_id = p_grupo_id
    group by p.id, g.nombre
    order by votos desc, p.numero, p.nombre
    limit greatest(1, least(coalesce(p_limite, 100), 1000));
end;
$$;

create or replace function public.listar_administradores()
returns table (correo text, agregado_por text, agregado_en timestamptz)
language plpgsql stable security definer set search_path = ''
as $$
#variable_conflict use_column
begin
  perform public._exigir_admin();
  return query select a.correo, a.agregado_por, a.agregado_en from public.administradores a order by a.agregado_en;
end;
$$;

create or replace function public.agregar_administrador(p_correo text)
returns void
language plpgsql volatile security definer set search_path = ''
as $$
declare v text := lower(btrim(coalesce(p_correo, '')));
begin
  perform public._exigir_admin();
  if v !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Ese correo no parece válido' using errcode = '22023';
  end if;
  insert into public.administradores (correo, agregado_por)
  values (v, lower(auth.jwt() ->> 'email'))
  on conflict (correo) do nothing;
end;
$$;

-- No puedes quitarte a ti mismo: así siempre queda al menos un administrador.
create or replace function public.quitar_administrador(p_correo text)
returns void
language plpgsql volatile security definer set search_path = ''
as $$
declare v text := lower(btrim(coalesce(p_correo, '')));
begin
  perform public._exigir_admin();
  if v = lower(auth.jwt() ->> 'email') then
    raise exception 'No puedes quitarte a ti mismo como administrador' using errcode = '22023';
  end if;
  delete from public.administradores where correo = v;
end;
$$;

-- Quién puede llamar cada función (los visitantes sin verificar, ninguna).
revoke execute on function public.es_admin(), public._exigir_admin(),
  public.emitir_voto(bigint, text), public.resumen_votos(), public.ranking_personajes(int, int),
  public.listar_administradores(), public.agregar_administrador(text), public.quitar_administrador(text)
  from public, anon;
grant execute on function public.es_admin(),
  public.emitir_voto(bigint, text), public.resumen_votos(), public.ranking_personajes(int, int),
  public.listar_administradores(), public.agregar_administrador(text), public.quitar_administrador(text)
  to authenticated;
